#!/usr/bin/env python3
"""Generate the Kotlin register/PLL tables for the dtr100 driver from decompiled/3.26/tables.json.

Only the DAB (band III) tables are emitted; the FM table is deliberately left out (FM is out of scope).
usage: .venv/bin/python tools/gen_kotlin_tables.py > android/driver-dtr100/src/main/kotlin/io/github/jvspier/dabplay/driver/dtr100/Dtr100Tables.kt
"""
import json
import os

t = json.load(open(os.path.join(os.path.dirname(__file__), "..", "decompiled", "3.26", "tables.json")))


def pairs(name, key):
    flat = ", ".join(f"0x{r:02X}, 0x{v:02X}" for r, v in t[key])
    return f"    /** {key}: (register, value) pairs */\n    val {name} = intArrayOf({flat})\n"


def ints(name, key, n=None, fmt="0x{:X}"):
    vals = t[key][:n] if n else t[key]
    return f"    val {name} = intArrayOf({', '.join(fmt.format(v) for v in vals)})\n"


print("""package io.github.jvspier.dabplay.driver.dtr100

// GENERATED by tools/gen_kotlin_tables.py from the vendor libdab.so (see docs/protocol.md). Do not edit.
// Register and PLL tables needed to drive the chip; values are functional data (interoperability).

internal object Dtr100Tables {""")
print(pairs("RF_INIT_DAB", "rf_init_dab_pairs"))
print(pairs("RF_INIT_DAB_TAIL", "rf_init_dab_tail"))
print(pairs("RF_BAND3", "rf_band3_pairs"))
print("    /** clock_plans: 7 bytes each → page 0x0F regs 0xE8..0xEE; 0xFF in byte 0 = invalid plan */")
print("    val CLOCK_PLANS = arrayOf(" + ", ".join("intArrayOf(" + ", ".join(f"0x{b:02X}" for b in p) + ")" for p in t["clock_plans"]) + ")")
print("    /** band III: PLL word and clock plan per channel index (41 entries, 5A..13F incl. N channels) */")
print(ints("BAND3_PLL", "band3_pll", 41))
print(ints("BAND3_PLAN", "band3_plan", 41, "{}"))
print("}")
