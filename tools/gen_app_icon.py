#!/usr/bin/env python3
"""DABplay+ app icon (design D4+, chosen 2026-10-06): "DAB+" with an orange underline over a faint play triangle, on navy.

One drawing, written as the adaptive-icon vector drawables (background, foreground, monochrome), the notification
icon, and a 512 x 512 PNG for the Play Store / GitHub (needs ImageMagick with librsvg). Canvas: 108 x 108 units, of
which launchers show the middle 72 (circle, squircle, ...); everything that matters stays in the middle 66.
The letters are real glyph outlines of the app's Inter SemiBold, shaped with HarfBuzz (kerning as in a browser).

    pip install fonttools uharfbuzz
    python3 tools/gen_app_icon.py
"""
import math
import os
import subprocess

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

MAIN = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "android", "app", "src", "main")
FONT = os.path.join(MAIN, "res", "font", "inter_semibold.ttf")

NAVY_FROM, NAVY_TO = "#2A2D44", "#161826"
PLAY_FROM, PLAY_TO = "#FF8A4C", "#FF5A36"
ORANGE, WHITE = "#FF6A3D", "#FFFFFF"
TRIANGLE_ALPHA = 0.12


def text_path(text, cx, baseline, size, tracking):
    """Glyph outlines of [text] centred on [cx], shaped like a browser would (kerning), in icon units."""
    blob = hb.Blob.from_file_path(FONT)
    font = hb.Font(hb.Face(blob))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf)
    tt = TTFont(FONT)
    glyphs = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    upem = tt["head"].unitsPerEm
    scale = size / upem
    advances = [p.x_advance * scale + tracking for p in buf.glyph_positions]
    width = sum(advances)              # the browser's text-anchor="middle" includes the last letter's tracking
    x = cx - width / 2
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    for info, pos, adv in zip(buf.glyph_infos, buf.glyph_positions, advances):
        name = order[info.codepoint]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x + pos.x_offset * scale, baseline)))
        x += adv
    return pen.getCommands()


def rounded_polygon(points, r):
    """[points] grown by [r] with round corners (one fill, so a translucent shape has no darker seams)."""
    n = len(points)
    cmds = []
    for i in range(n):
        p0, p1, p2 = points[i - 1], points[i], points[(i + 1) % n]
        def normal(a, b):
            dx, dy = b[0] - a[0], b[1] - a[1]
            l = math.hypot(dx, dy)
            return dy / l, -dx / l                      # outward for a clockwise polygon (y down)
        n_in, n_out = normal(p0, p1), normal(p1, p2)
        a = (p1[0] + n_in[0] * r, p1[1] + n_in[1] * r)
        b = (p1[0] + n_out[0] * r, p1[1] + n_out[1] * r)
        cmds.append(f"{'M' if i == 0 else 'L'}{a[0]:.2f},{a[1]:.2f}")
        cmds.append(f"A{r},{r} 0 0,1 {b[0]:.2f},{b[1]:.2f}")
    return " ".join(cmds) + " Z"


def rounded_rect(x, y, w, h, r):
    return (f"M{x + r},{y} h{w - 2 * r} a{r},{r} 0 0,1 0,{2 * r} h{-(w - 2 * r)} a{r},{r} 0 0,1 0,{-2 * r} Z"
            if h == 2 * r else None)


DAB = text_path("DAB", cx=46, baseline=60, size=17, tracking=-0.3)
TRIANGLE = rounded_polygon([(41, 30), (80, 54), (41, 78)], 4)
PLUS = "M73.5,47 v9 M69,51.5 h9"                       # stroked, round caps
PLUS_W = 3.6
UNDERLINE = rounded_rect(33, 64.5, 42, 3.2, 1.6)
BG = "M0,0 h108 v108 h-108 Z"


def svg(view="0 0 108 108"):
    view = f'viewBox="{view}"'
    return f"""<svg xmlns="http://www.w3.org/2000/svg" {view}>
  <defs>
    <linearGradient id="navy" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{NAVY_FROM}"/><stop offset="1" stop-color="{NAVY_TO}"/></linearGradient>
    <linearGradient id="play" x1="33" y1="64.5" x2="75" y2="67.7" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{PLAY_FROM}"/><stop offset="1" stop-color="{PLAY_TO}"/></linearGradient>
  </defs>
  <path d="{BG}" fill="url(#navy)"/>
  <path d="{TRIANGLE}" fill="{WHITE}" fill-opacity="{TRIANGLE_ALPHA}"/>
  <path d="{DAB}" fill="{WHITE}"/>
  <path d="{PLUS}" stroke="{ORANGE}" stroke-width="{PLUS_W}" stroke-linecap="round" fill="none"/>
  <path d="{UNDERLINE}" fill="url(#play)"/>
</svg>
"""


def gradient(start, end, c0, c1):
    return f"""<aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{start[0]}" android:startY="{start[1]}" android:endX="{end[0]}" android:endY="{end[1]}">
                <item android:offset="0" android:color="#FF{c0[1:]}"/>
                <item android:offset="1" android:color="#FF{c1[1:]}"/>
            </gradient>
        </aapt:attr>"""


HEADER = "<!-- Generated by tools/gen_app_icon.py: change the drawing there, not here. -->\n"


def vector(body, w=108, vw=108, vx=0):
    group = f'\n    <group android:translateX="{-vx}" android:translateY="{-vx}">{body}\n    </group>' if vx else body
    return f"""{HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{w}dp" android:height="{w}dp"
    android:viewportWidth="{vw}" android:viewportHeight="{vw}">{group}
</vector>
"""


def fill(d, color, alpha=None):
    a = f' android:fillAlpha="{alpha}"' if alpha is not None else ""
    return f'\n    <path android:fillColor="#FF{color[1:]}"{a} android:pathData="{d}"/>'


def stroke(d, color):
    return (f'\n    <path android:strokeColor="#FF{color[1:]}" android:strokeWidth="{PLUS_W}" android:strokeLineCap="round"'
            f' android:pathData="{d}"/>')


def gradient_fill(d, start, end, c0, c1):
    return f'\n    <path android:pathData="{d}">\n        {gradient(start, end, c0, c1)}\n    </path>'


background = vector(gradient_fill(BG, (0, 0), (108, 108), NAVY_FROM, NAVY_TO) + fill(TRIANGLE, WHITE, TRIANGLE_ALPHA))
foreground = vector(fill(DAB, WHITE) + stroke(PLUS, ORANGE) + gradient_fill(UNDERLINE, (33, 64.5), (75, 67.7), PLAY_FROM, PLAY_TO))
monochrome = vector(fill(DAB, WHITE) + stroke(PLUS, WHITE) + fill(UNDERLINE, WHITE))
# Status bar: the same mark, cropped to its middle (24dp, white; the system tints it)
notification = vector(fill(DAB, WHITE) + stroke(PLUS, WHITE) + fill(UNDERLINE, WHITE), w=24, vw=52, vx=28)

drawable = os.path.join(MAIN, "res", "drawable")
for name, text in [("ic_launcher_background.xml", background), ("ic_launcher_foreground.xml", foreground),
                   ("ic_launcher_monochrome.xml", monochrome), ("ic_notification.xml", notification)]:
    with open(os.path.join(drawable, name), "w") as f:
        f.write(text)
# Store icon: what a launcher shows (the middle 72), full square; the stores round the corners themselves
png = os.path.join(MAIN, "ic_launcher-playstore.png")
subprocess.run(["magick", "-background", "none", "-density", "1200", "svg:-", "-resize", "512x512", png],
               input=svg("18 18 72 72").encode(), check=True)
print("written:", drawable, png)
